/**
 * Builds a standalone Python crawler from the tool's settings.
 *
 * This exists because a browser cannot fetch arbitrary cross-origin pages —
 * CORS forbids reading the response. A local Python process has no such
 * limit, so for a real site-wide crawl the honest answer is to hand the user
 * a script rather than pretend the browser can do it.
 */

/** Quote a JS string as a Python literal. */
function py(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** Render a JS array of strings as a Python list literal. */
function pyList(values, indent = "    ") {
  if (values.length === 0) return "[]";
  return `[\n${values.map((v) => `${indent}${py(v)},`).join("\n")}\n]`;
}

/**
 * @param {object} settings the tool's current option values
 * @returns {string} runnable Python source
 */
export function buildPythonScript(settings) {
  const {
    startUrl,
    scope,
    maxPages,
    delay,
    contentSelector,
    stripSelectors,
    excludePatterns,
    outputName,
    renderJs,
    respectRobots,
    includeToc,
  } = settings;

  let origin = "";
  let pathPrefix = "/";
  try {
    const parsed = new URL(startUrl);
    origin = parsed.origin;
    pathPrefix = parsed.pathname || "/";
  } catch {
    origin = startUrl;
  }

  const strip = stripSelectors.filter(Boolean);
  const exclude = excludePatterns.filter(Boolean);

  const deps = renderJs
    ? "pip install playwright beautifulsoup4 markdownify\n#     playwright install chromium"
    : "pip install requests beautifulsoup4 markdownify";

  return `#!/usr/bin/env python3
"""
Crawl ${startUrl} and save every page into one Markdown file.

Generated by Tool Hub — Site to Markdown.
Edit the CONFIG block below to re-target it at another site.

Setup:
    ${deps}

Run:
    python ${outputName.replace(/\.md$/, "")}.py

Output:
    ${outputName}
"""

import re
import sys
import time
from collections import deque
from urllib.parse import urljoin, urlparse
${respectRobots ? "from urllib.robotparser import RobotFileParser\n" : ""}
from bs4 import BeautifulSoup
from markdownify import markdownify as md
${renderJs ? "from playwright.sync_api import sync_playwright" : "import requests"}

# ----------------------------------------------------------------- CONFIG

START_URL = ${py(startUrl)}
ORIGIN = ${py(origin)}
# Only follow links whose path starts with this. "/" crawls the whole host.
PATH_PREFIX = ${py(scope === "prefix" ? pathPrefix : "/")}
OUTPUT_FILE = ${py(outputName)}

MAX_PAGES = ${maxPages}
REQUEST_DELAY = ${delay}          # seconds between requests — be a good citizen
TIMEOUT = 20
RESPECT_ROBOTS = ${respectRobots ? "True" : "False"}
INCLUDE_TOC = ${includeToc ? "True" : "False"}

USER_AGENT = "Mozilla/5.0 (compatible; ToolHubDocsArchiver/1.0)"

# Where the article body lives. Empty string = try the list below in order.
CONTENT_SELECTOR = ${py(contentSelector)}
CONTENT_CANDIDATES = [
    "main",
    "article",
    '[role="main"]',
    ".markdown-body",
    ".rm-Article",
    ".theme-doc-markdown",
    ".content",
    "#content",
]

# Removed before conversion — navigation, chrome, anything non-article.
STRIP_SELECTORS = ${pyList(
    [
      "script",
      "style",
      "noscript",
      "iframe",
      "svg",
      "nav",
      "header",
      "footer",
      "aside",
      "form",
      "button",
      ...strip,
    ]
  )}

# URLs matching any of these regexes are never fetched.
EXCLUDE_PATTERNS = ${pyList(exclude)}

# --------------------------------------------------------------- CRAWLER


def is_in_scope(url: str) -> bool:
    parsed = urlparse(url)
    if f"{parsed.scheme}://{parsed.netloc}" != ORIGIN:
        return False
    if not parsed.path.startswith(PATH_PREFIX):
        return False
    return not any(re.search(p, url) for p in EXCLUDE_PATTERNS)


def normalize(url: str) -> str:
    """Drop fragment and query so one page isn't crawled under two URLs."""
    parsed = urlparse(url)._replace(fragment="", query="")
    return parsed.geturl().rstrip("/")


def pick_content(soup: BeautifulSoup):
    if CONTENT_SELECTOR:
        found = soup.select_one(CONTENT_SELECTOR)
        if found:
            return found
    for selector in CONTENT_CANDIDATES:
        found = soup.select_one(selector)
        # Skip empty shells — some sites wrap everything in an unused <main>.
        if found and len(found.get_text(strip=True)) > 200:
            return found
    return soup.body or soup


def absolutize(soup: BeautifulSoup, base: str) -> None:
    """Make links and images absolute so the archive works on its own."""
    for tag, attr in (("a", "href"), ("img", "src")):
        for node in soup.find_all(tag):
            value = node.get(attr)
            if value and not value.startswith("data:"):
                node[attr] = urljoin(base, value)
${
  renderJs
    ? `

def make_fetcher():
    """Render each page in a real browser, for JS-built docs sites."""
    playwright = sync_playwright().start()
    browser = playwright.chromium.launch()
    page = browser.new_page(user_agent=USER_AGENT)

    def fetch(url: str):
        page.goto(url, wait_until="networkidle", timeout=TIMEOUT * 1000)
        return page.content()

    def close():
        browser.close()
        playwright.stop()

    return fetch, close
`
    : `

def make_fetcher():
    session = requests.Session()
    session.headers.update({"User-Agent": USER_AGENT})

    def fetch(url: str):
        response = session.get(url, timeout=TIMEOUT)
        response.raise_for_status()
        if "text/html" not in response.headers.get("Content-Type", ""):
            return None
        return response.text

    return fetch, lambda: None
`
}

def load_robots():
    if not RESPECT_ROBOTS:
        return None
    parser = RobotFileParser()
    parser.set_url(urljoin(ORIGIN, "/robots.txt"))
    try:
        parser.read()
        return parser
    except Exception as error:
        print(f"  [warn] could not read robots.txt ({error}); continuing")
        return None


def crawl():
    fetch, close = make_fetcher()
    robots = load_robots()

    visited, pages = set(), []
    queue = deque([normalize(START_URL)])

    try:
        while queue and len(pages) < MAX_PAGES:
            url = queue.popleft()
            if url in visited:
                continue
            visited.add(url)

            if robots and not robots.can_fetch(USER_AGENT, url):
                print(f"  [robots] skipping {url}")
                continue

            try:
                html = fetch(url)
            except Exception as error:
                print(f"  [skip] {url} -> {error}")
                continue
            if html is None:
                continue

            soup = BeautifulSoup(html, "html.parser")
            heading = soup.find("h1") or soup.find("title")
            title = heading.get_text(strip=True) if heading else url

            for link in soup.find_all("a", href=True):
                target = normalize(urljoin(url, link["href"]))
                if is_in_scope(target) and target not in visited:
                    queue.append(target)

            content = pick_content(soup)
            for selector in STRIP_SELECTORS:
                for node in content.select(selector):
                    node.decompose()
            absolutize(content, url)

            body = md(str(content), heading_style="ATX", bullets="-").strip()
            body = re.sub(r"\\n{3,}", "\\n\\n", body)
            body = nest_headings(body, title).strip()

            pages.append((url, title, body))
            print(f"[{len(pages)}/{MAX_PAGES}] {title} — {url}")

            time.sleep(REQUEST_DELAY)
    except KeyboardInterrupt:
        print("\\nInterrupted — writing what we have so far.")
    finally:
        close()

    return pages


def nest_headings(markdown: str, title: str) -> str:
    """Fit a page's headings under the "## <title>" the archive gives it.

    Drops a leading H1 that merely repeats the title, then pushes every other
    heading down one level so the combined file has a real hierarchy.
    Headings inside fenced code blocks are left alone.
    """
    def norm(text):
        return re.sub(r"\\s+", " ", text).strip().lower()

    fence = "\`" * 3
    out, in_fence, seen = [], False, False

    for line in markdown.split("\\n"):
        stripped = line.lstrip()
        if stripped.startswith(fence) or stripped.startswith("~~~"):
            in_fence = not in_fence
            seen = True
            out.append(line)
            continue

        match = None if in_fence else re.match(r"^(#{1,6})\\s+(.*)$", line)
        if not match:
            if line.strip():
                seen = True
            out.append(line)
            continue

        hashes, text = match.group(1), match.group(2)
        if not seen and len(hashes) == 1 and norm(text) == norm(title):
            continue

        seen = True
        out.append("#" * min(6, len(hashes) + 1) + " " + text)

    return "\\n".join(out).lstrip("\\n")


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def save(pages):
    if not pages:
        print("No pages captured. Nothing written.")
        return

    with open(OUTPUT_FILE, "w", encoding="utf-8") as handle:
        handle.write(f"# Archive of {ORIGIN}\\n\\n")
        handle.write(f"Source: {START_URL}  \\n")
        handle.write(f"Pages: {len(pages)}\\n\\n")

        if INCLUDE_TOC:
            handle.write("## Contents\\n\\n")
            for _, title, _ in pages:
                handle.write(f"- [{title}](#{slugify(title)})\\n")
            handle.write("\\n")

        handle.write("---\\n\\n")
        for url, title, body in pages:
            handle.write(f"## {title}\\n\\n")
            handle.write(f"*Source: {url}*\\n\\n")
            handle.write(body)
            handle.write("\\n\\n---\\n\\n")

    characters = sum(len(body) for _, _, body in pages)
    print(f"\\nSaved {len(pages)} pages to {OUTPUT_FILE}")
    print(f"~{characters:,} characters (~{characters // 4:,} tokens)")


if __name__ == "__main__":
    print(f"Crawling {START_URL}")
    print(f"Scope: {ORIGIN}{PATH_PREFIX}  |  cap: {MAX_PAGES} pages")
    try:
        save(crawl())
    except Exception as error:
        print(f"Failed: {error}", file=sys.stderr)
        sys.exit(1)
`;
}
